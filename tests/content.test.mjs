// Canon preservation tests. The original PARADISE site (snapshot in
// tests/fixtures/v1) is the source of truth: every line of Thai lore in it
// must appear unchanged in V2, and V2 must not add Thai lore of its own.
import { test, before } from 'node:test';
import assert from 'node:assert/strict';
import { readFile, readdir, stat } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from '../scripts/build.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const FIX = join(ROOT, 'tests', 'fixtures', 'v1');
const DIST = join(ROOT, 'dist');
const THAI = /[฀-๿]/;

const ENTITIES = { amp: '&', nbsp: ' ', lt: '<', gt: '>', quot: '"', '#39': "'", apos: "'" };
const decode = (s) => s.replace(/&(#?\w+);/g, (m, k) => (k in ENTITIES ? ENTITIES[k] : m));
const INLINE = /^(?:strong|em|b|i|span|a|br|output)$/i;

/** Visible text, one block per line; inline tags do not break a sentence. */
function textLines(html) {
  const body = html.replace(/<script[\s\S]*?<\/script>/gi, '').replace(/<style[\s\S]*?<\/style>/gi, '').replace(/<!--[\s\S]*?-->/g, '');
  const flat = body.replace(/<\/?([a-zA-Z0-9]+)\b[^>]*>/g, (m, tag) => (tag.toLowerCase() === 'br' ? ' ' : INLINE.test(tag) ? '' : '\n'));
  return decode(flat).split('\n').map((l) => l.replace(/\s+/g, ' ').trim()).filter(Boolean);
}

/** Thai string literals in JS source; template literals are split around ${…}. */
function thaiLiterals(js) {
  const out = [];
  for (const m of js.matchAll(/'((?:[^'\\\n]|\\.)*)'|`((?:[^`\\]|\\.)*)`/g)) {
    const s = m[1] ?? m[2];
    if (!THAI.test(s)) continue;
    s.split(/\$\{[^}]*\}/).map((p) => p.trim()).filter((p) => THAI.test(p)).forEach((p) => out.push(p));
  }
  return out;
}

async function walk(dir) {
  const out = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) out.push(...await walk(p)); else out.push(p);
  }
  return out;
}

let v1Html, v1Js, v2Html, v2Js, v2Lines;
before(async () => {
  await build();
  v1Html = await readFile(join(FIX, 'index.html'), 'utf8');
  v1Js = await readFile(join(FIX, 'main.js'), 'utf8');
  v2Html = await readFile(join(DIST, 'index.html'), 'utf8');
  const files = (await walk(join(DIST, 'js'))).filter((f) => f.endsWith('.js'));
  v2Js = (await Promise.all(files.map((f) => readFile(f, 'utf8')))).join('\n');
  v2Lines = textLines(v2Html);
});

test('every Thai line of the original page appears unchanged in V2', () => {
  const v2Text = v2Lines.join('\n');
  const missing = textLines(v1Html).filter((l) => THAI.test(l)).filter((l) => !v2Text.includes(l));
  assert.deepEqual(missing, [], `Missing or altered Thai text:\n${missing.join('\n')}`);
});

test('every Thai string generated by the original scripts appears unchanged in V2', () => {
  const missing = thaiLiterals(v1Js).filter((s) => !v2Js.includes(s));
  assert.deepEqual(missing, [], `Missing or altered dynamic Thai text:\n${missing.join('\n')}`);
});

test('V2 adds no Thai lore that is not in the original', () => {
  const v1Text = textLines(v1Html).join('\n') + '\n' + thaiLiterals(v1Js).join('\n');
  const added = v2Lines.filter((l) => THAI.test(l)).filter((l) => !v1Text.includes(l));
  const addedJs = thaiLiterals(v2Js).filter((s) => !v1Text.includes(s));
  assert.deepEqual([...added, ...addedJs], [], `Thai text not found in the original:\n${[...added, ...addedJs].join('\n')}`);
});

test('all four artist profile URLs are preserved and open safely', () => {
  const urls = [...v1Html.matchAll(/href="(https:\/\/www\.facebook\.com\/[^"]+)"/g)].map((m) => m[1]);
  assert.equal(urls.length, 4);
  for (const u of urls) {
    const tag = v2Html.match(new RegExp(`<a[^>]*href="${u.replace(/[.?*+^$()[\]{}|\\]/g, '\\$&')}"[^>]*>`));
    assert.ok(tag, `Artist link missing: ${u}`);
    assert.match(tag[0], /target="_blank"/);
    assert.match(tag[0], /rel="noopener noreferrer"/);
  }
  for (const n of ['Artist 01', 'Artist 02', 'Artist 03', 'Artist 04']) assert.ok(v2Html.includes(n), n);
});

test('TST Project attribution and the fan-work disclaimer are present', () => {
  const text = v2Lines.join('\n');
  assert.match(text, /Created by TST Project/);
  assert.match(text, /Unofficial Fan-Made OC × Marvel Project/);
  assert.match(text, /Not affiliated with or endorsed by Marvel/);
});

test('every original room, door and secret hook exists in V2', () => {
  const roomIds = [...v1Html.matchAll(/<section id="([^"]+)"[^>]*data-room/g)].map((m) => m[1]);
  assert.equal(roomIds.length, 10);
  for (const id of roomIds) assert.match(v2Html, new RegExp(`<section id="${id}"[^>]*data-room`), `room ${id}`);
  const doors = [...v1Html.matchAll(/class="door[^"]*" href="#([^"]+)"/g)].map((m) => m[1]);
  for (const d of doors) assert.match(v2Html, new RegExp(`class="door[^"]*" href="#${d}"`), `door ${d}`);
  for (const hook of ['data-apple', 'data-enter', 'data-skip-fall', 'data-inscription', 'data-contract-seal', 'data-break-seal',
    'data-floor="X"', 'data-keyfind', 'data-locked', 'data-office-toggle', 'data-mask-toggle', 'data-sound-toggle',
    'data-serpent-host="wander"', 'data-serpent-host="divider"', 'data-serpent-host="spine"', 'data-lightbox', 'data-secret-count']) {
    assert.ok(v2Html.includes(hook), hook);
  }
});

test('the gallery and lightbox show all eight artworks, and every file exists', async () => {
  const opens = new Set([...v2Html.matchAll(/data-lightbox-open="(\d+)"/g)].map((m) => +m[1]));
  assert.deepEqual([...opens].sort(), [0, 1, 2, 3, 4, 5, 6, 7]);
  const { ART } = await import(join(ROOT, 'src', 'js', 'data', 'art.js').replace(/\\/g, '/').replace(/^([A-Za-z]):/, 'file:///$1:'));
  assert.equal(ART.length, 8);
  for (const a of ART) await stat(join(DIST, a.src));
});
